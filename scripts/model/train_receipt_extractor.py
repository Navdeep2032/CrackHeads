#!/usr/bin/env python3
"""Donut fine-tuning for SplitSnap receipt extraction.

The training target is the unified SplitSnap receipt schema generated by
``prepare_dataset.py``. This keeps CORD and SROIE targets consistent.

Usage:
    python scripts/model/train_receipt_extractor.py --epochs 1 --max-samples 20
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path
from typing import Any, Dict, List, Sequence

import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset
from transformers import DonutProcessor, VisionEncoderDecoderModel


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Fine-tune a Donut baseline for receipt extraction")
    parser.add_argument("--train-manifest", default="data/processed/train.jsonl")
    parser.add_argument("--validation-manifest", default="data/processed/validation.jsonl")
    parser.add_argument(
        "--synthetic-manifest",
        default="",
        help="Optional synthetic records.jsonl to append to the training set only",
    )
    parser.add_argument(
        "--max-synthetic-samples",
        type=int,
        default=0,
        help="Maximum synthetic records to append; 0 uses all synthetic records",
    )
    parser.add_argument(
        "--source",
        choices=["all", "cord", "sroie"],
        default="all",
        help="Train on all sources or one source only",
    )
    parser.add_argument("--epochs", type=int, default=1)
    parser.add_argument("--batch-size", type=int, default=2)
    parser.add_argument("--max-samples", type=int, default=0)
    parser.add_argument("--learning-rate", type=float, default=5e-5)
    parser.add_argument("--output-dir", default="models/receipt_extractor_experiment")
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--image-height", type=int, default=640)
    parser.add_argument("--image-width", type=int, default=480)
    parser.add_argument(
        "--mixed-precision",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Use CUDA automatic mixed precision to reduce GPU memory usage",
    )
    return parser.parse_args()


def read_manifest(path: str) -> List[Dict[str, Any]]:
    manifest_path = Path(path)
    if not manifest_path.is_file():
        raise FileNotFoundError(f"Manifest does not exist: {manifest_path}")
    rows: List[Dict[str, Any]] = []
    with manifest_path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            row = json.loads(line)
            if "image" not in row or "receipt" not in row:
                raise ValueError(f"Invalid manifest row at {manifest_path}:{line_number}")
            image_path = Path(row["image"])
            if not image_path.is_absolute():
                row["image"] = str((manifest_path.parent / "images" / image_path).resolve())
            rows.append(row)
    return rows


class ReceiptDataset(Dataset):
    def __init__(self, rows: Sequence[Dict[str, Any]]):
        self.rows = list(rows)

    def __len__(self) -> int:
        return len(self.rows)

    def __getitem__(self, index: int) -> Dict[str, Any]:
        row = self.rows[index]
        image_path = Path(row["image"])
        if not image_path.is_file():
            raise FileNotFoundError(f"Manifest image does not exist: {image_path}")
        image = Image.open(image_path).convert("RGB")
        target = json.dumps(row["receipt"], ensure_ascii=False, separators=(",", ":"))
        return {"image": image, "target": target}


def collate_fn(batch: Sequence[Dict[str, Any]], processor: DonutProcessor):
    images = [item["image"] for item in batch]
    targets = [item["target"] for item in batch]
    encoded = processor(images=images, text=targets, return_tensors="pt", padding=True)
    labels = encoded["labels"].clone()
    pad_token_id = processor.tokenizer.pad_token_id
    labels[labels == pad_token_id] = -100
    encoded["labels"] = labels
    return encoded


def build_model_and_processor(device: str, image_height: int, image_width: int):
    model_name = "naver-clova-ix/donut-base"
    processor = DonutProcessor.from_pretrained(model_name)
    processor.image_processor.size = {"height": image_height, "width": image_width}
    model = VisionEncoderDecoderModel.from_pretrained(model_name)
    model.config.pad_token_id = processor.tokenizer.pad_token_id
    model.config.decoder_start_token_id = processor.tokenizer.convert_tokens_to_ids(["<s>"])[0]
    model.config.eos_token_id = processor.tokenizer.convert_tokens_to_ids(["</s>"])[0]
    model.to(device)
    return processor, model


def train_one_epoch(model, loader, optimizer, device, mixed_precision: bool):
    model.train()
    total_loss = 0.0
    steps = 0
    for batch in loader:
        batch = {k: v.to(device) if isinstance(v, torch.Tensor) else v for k, v in batch.items()}
        with torch.autocast(
            device_type="cuda",
            dtype=torch.float16,
            enabled=mixed_precision and device.startswith("cuda"),
        ):
            outputs = model(**batch)
        loss = outputs.loss
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()
        total_loss += loss.item()
        steps += 1
    return total_loss / max(steps, 1)


def evaluate(model, loader, device, mixed_precision: bool):
    model.eval()
    total_loss = 0.0
    steps = 0
    with torch.no_grad():
        for batch in loader:
            batch = {k: v.to(device) if isinstance(v, torch.Tensor) else v for k, v in batch.items()}
            with torch.autocast(
                device_type="cuda",
                dtype=torch.float16,
                enabled=mixed_precision and device.startswith("cuda"),
            ):
                outputs = model(**batch)
            total_loss += outputs.loss.item()
            steps += 1
    return total_loss / max(steps, 1)


def main() -> None:
    args = parse_args()
    random.seed(42)
    train_rows = read_manifest(args.train_manifest)
    val_rows = read_manifest(args.validation_manifest)
    if args.synthetic_manifest:
        synthetic_rows = read_manifest(args.synthetic_manifest)
        if args.max_synthetic_samples > 0:
            random.shuffle(synthetic_rows)
            synthetic_rows = synthetic_rows[: args.max_synthetic_samples]
        train_rows.extend(synthetic_rows)
    if args.source != "all":
        allowed_training_sources = {args.source}
        if args.source == "cord" and args.synthetic_manifest:
            allowed_training_sources.add("synthetic_indian")
        train_rows = [
            row for row in train_rows if row.get("source") in allowed_training_sources
        ]
        val_rows = [row for row in val_rows if row.get("source") == args.source]

    if args.max_samples and args.max_samples > 0:
        random.shuffle(train_rows)
        train_rows = train_rows[: args.max_samples]
        val_rows = val_rows[:max(1, args.max_samples // 2)]
    print(f"Training records: {len(train_rows)}")
    print(f"Validation records: {len(val_rows)}")

    processor, model = build_model_and_processor(
        args.device,
        args.image_height,
        args.image_width,
    )
    train_dataset = ReceiptDataset(train_rows)
    val_dataset = ReceiptDataset(val_rows)
    train_loader = DataLoader(train_dataset, batch_size=args.batch_size, shuffle=True, collate_fn=lambda batch: collate_fn(batch, processor))
    val_loader = DataLoader(val_dataset, batch_size=args.batch_size, shuffle=False, collate_fn=lambda batch: collate_fn(batch, processor))

    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    best_val_loss = float("inf")
    best_epoch = 0

    for epoch in range(args.epochs):
        train_loss = train_one_epoch(
            model,
            train_loader,
            optimizer,
            args.device,
            args.mixed_precision,
        )
        val_loss = evaluate(model, val_loader, args.device, args.mixed_precision)
        print(f"Epoch {epoch + 1}/{args.epochs}: train_loss={train_loss:.4f}, val_loss={val_loss:.4f}")
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_epoch = epoch + 1
            model.save_pretrained(output_dir)
            processor.save_pretrained(output_dir)
            print(f"Saved new best checkpoint at epoch {best_epoch}: val_loss={best_val_loss:.4f}")

    print(
        f"Saved best model checkpoint to: {output_dir} "
        f"(epoch {best_epoch}, val_loss={best_val_loss:.4f})"
    )


if __name__ == "__main__":
    main()
